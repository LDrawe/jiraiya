const REPO_ICONS: IconName[] = ['repo-grid', 'repo-palette', 'repo-megaphone', 'repo-sprout'];

export function pickRepositoryIcon(projectId: string, index: number): IconName {
  if (index === 0) return 'repo-grid';
  let hash = 0;
  for (let i = 0; i < projectId.length; i += 1) {
    hash = (hash * 31 + projectId.charCodeAt(i)) >>> 0;
  }
  return REPO_ICONS[(hash % (REPO_ICONS.length - 1)) + 1];
}
